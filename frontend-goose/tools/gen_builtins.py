#!/usr/bin/env python3
"""Generate src/builtins_gen.goose: the C types of clang-20's builtin functions.

For every name __has_builtin() accepts (see predef_gen.goose), clang is made
to reference it in a call with no arguments, and the type of the implicit
declaration is read back from `-Xclang -ast-dump`. Builtins with custom type
checking show up with a placeholder type ('void ()' or similar); goosecc
type-checks those itself (see BUILTIN_CUSTOM in sema).

The output is one line per builtin: `name|type|attrs` where attrs is a set
of letters from the ast dump (n = noreturn, c = const, p = pure, l = library
builtin, i.e. a plain C library name that is only predeclared when called).

usage: tools/gen_builtins.py [--clang clang-20]
"""
import argparse, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "builtins_gen.goose")
PREDEF = os.path.join(HERE, "..", "src", "predef_gen.goose")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--clang", default="clang-20")
    a = ap.parse_args()
    text = open(PREDEF).read()
    m = re.search(r'let HAS_BUILTIN = """\n(.*?)\n""";', text, re.S)
    names = [l.split()[0] for l in m.group(1).splitlines() if l.strip()]
    names = [n for n in names if not n.startswith("__is_") and not n.startswith("_Block")]
    src = []
    for i, n in enumerate(names):
        src.append("void goosecc_probe_%d(void) { %s(); }\n" % (i, n))
    with tempfile.NamedTemporaryFile("w", suffix=".c", delete=False) as f:
        f.write("".join(src))
        path = f.name
    r = subprocess.run([a.clang, "-fsyntax-only", "-w", "-ferror-limit=0", "-Xclang", "-ast-dump", "-fno-color-diagnostics", path],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    os.unlink(path)
    out = r.stdout.decode(errors="replace")
    types = {}
    # Implicit declarations of library builtins appear as FunctionDecl ... implicit
    for line in out.splitlines():
        mm = re.search(r"FunctionDecl 0x[0-9a-f]+ <[^>]*> (?:col:\d+ )?implicit (?:used )?(?:referenced )?(\w+) '([^']*)'(.*)", line)
        if mm:
            types.setdefault(mm.group(1), (mm.group(2), "l"))
            continue
        mm = re.search(r"DeclRefExpr 0x[0-9a-f]+ <[^>]*> '([^']*)' (?:lvalue )?Function 0x[0-9a-f]+ '(\w+)' '([^']*)'", line)
        if mm:
            types.setdefault(mm.group(2), (mm.group(3), ""))
    # Attributes: probe noreturn / const via clang's own knowledge is not in the
    # dump; take the well-known noreturn set.
    noreturn = {"abort", "exit", "_Exit", "_exit", "__builtin_trap", "__builtin_unreachable", "__builtin_abort",
                "longjmp", "_longjmp", "siglongjmp", "__builtin_longjmp", "__builtin_debugtrap", "quick_exit"}
    lines = []
    for n in names:
        if n in types:
            t, f = types[n]
            if n in noreturn:
                f += "n"
            lines.append("%s|%s|%s" % (n, t, f))
    print(f"{len(lines)} of {len(names)} builtins typed", file=sys.stderr)
    missing = [n for n in names if n not in types]
    print("untyped:", " ".join(missing[:40]), "...", file=sys.stderr)
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gen_builtins.py from clang-20. Do not edit.\n")
        f.write("// name|type|flags (l = library function, n = noreturn)\n")
        f.write('let BUILTIN_TYPES = """\n' + "\n".join(lines) + '\n""";\n')


if __name__ == "__main__":
    main()
