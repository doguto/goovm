#!/usr/bin/env python3
"""Generate src/builtins_gen.goose: the C types of clang-20's builtin functions.

For every name __has_builtin() accepts (see predef_gen.goose), clang is made
to reference it in a call with no arguments, and the type of the implicit
declaration is read back from `-Xclang -ast-dump`. Builtins with custom type
checking show up with a placeholder type ('void ()' or similar); goosecc
type-checks those itself (see BUILTIN_CUSTOM in sema).

The output is one line per builtin: `name|type|attrs` where attrs is a set
of letters from the ast dump (n = noreturn, c = const, p = pure, l = library
builtin, i.e. a plain C library name that is only predeclared when called).

Builtins whose type involves FILE (__builtin_fprintf, ...) are typed by clang
only once a FILE typedef is visible; they are probed a second time with one
declared and recorded with that type: goosecc resolves FILE when it builds
the type at the call (and treats the builtin as unprototyped without it).

With --a64 (milestone F1) it writes src/builtins_a64_gen.goose instead: the
lines of the builtins whose type differs for --target=aarch64-linux-gnu
(va_list is struct __va_list there, passed by reference to va_start, va_copy
and va_end: written `__builtin_va_list *`), and of the builtins only AArch64
has (__builtin_arm_*, __builtin_neon_*, ...; the names of predef_a64_gen.goose).

usage: tools/gen_builtins.py [--clang clang-20] [--a64]
"""
import argparse, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "builtins_gen.goose")
PREDEF = os.path.join(HERE, "..", "src", "predef_gen.goose")


def probe(clang, names, prelude, flags=()):
    src = [prelude]
    for i, n in enumerate(names):
        src.append("void goosecc_probe_%d(void) { %s(); }\n" % (i, n))
    with tempfile.NamedTemporaryFile("w", suffix=".c", delete=False) as f:
        f.write("".join(src))
        path = f.name
    r = subprocess.run([clang] + list(flags) + ["-fsyntax-only", "-w", "-ferror-limit=0", "-Xclang", "-ast-dump", "-fno-color-diagnostics", path],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    os.unlink(path)
    out = r.stdout.decode(errors="replace")
    types = {}
    # Implicit declarations of library builtins appear as FunctionDecl ... implicit
    for line in out.splitlines():
        mm = re.search(r"FunctionDecl 0x[0-9a-f]+ <[^>]*> (?:col:\d+ )?implicit (?:used )?(?:referenced )?(\w+) '([^']*)'(.*)", line)
        if mm:
            types.setdefault(mm.group(1), (mm.group(2), "l"))
            continue
        mm = re.search(r"DeclRefExpr 0x[0-9a-f]+ <[^>]*> '([^']*)' (?:lvalue )?Function 0x[0-9a-f]+ '(\w+)' '([^']*)'", line)
        if mm:
            types.setdefault(mm.group(2), (mm.group(3), ""))
    return types


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--clang", default="clang-20")
    ap.add_argument("--a64", action="store_true")
    a = ap.parse_args()
    if a.a64:
        return main_a64(a)
    text = open(PREDEF).read()
    m = re.search(r'let HAS_BUILTIN = """\n(.*?)\n""";', text, re.S)
    names = [l.split()[0] for l in m.group(1).splitlines() if l.strip()]
    names = [n for n in names if not n.startswith("__is_") and not n.startswith("_Block")]
    types = probe(a.clang, names, "")
    with_file = probe(a.clang, names, "typedef struct _IO_FILE FILE;\n")
    for n, (t, f) in with_file.items():
        if "FILE" in t and types.get(n, ("", ""))[0] != t:
            types[n] = (t, f)
    # Attributes: probe noreturn / const via clang's own knowledge is not in the
    # dump; take the well-known noreturn set.
    noreturn = {"abort", "exit", "_Exit", "_exit", "__builtin_trap", "__builtin_unreachable", "__builtin_abort",
                "longjmp", "_longjmp", "siglongjmp", "__builtin_longjmp", "__builtin_debugtrap", "quick_exit"}
    lines = []
    for n in names:
        if n in types:
            t, f = types[n]
            if n in noreturn:
                f += "n"
            lines.append("%s|%s|%s" % (n, t, f))
    print(f"{len(lines)} of {len(names)} builtins typed", file=sys.stderr)
    missing = [n for n in names if n not in types]
    print("untyped:", " ".join(missing[:40]), "...", file=sys.stderr)
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gen_builtins.py from clang-20. Do not edit.\n")
        f.write("// name|type|flags (l = library function, n = noreturn)\n")
        f.write('let BUILTIN_TYPES = """\n' + "\n".join(lines) + '\n""";\n')


def main_a64(a):
    flags = ["--target=aarch64-linux-gnu"]
    x86 = {}
    text = open(OUT).read()
    m = re.search(r'let BUILTIN_TYPES = """\n(.*?)\n""";', text, re.S)
    for l in m.group(1).splitlines():
        n, t, f = l.split("|")
        x86[n] = (t, f)
    d = open(os.path.join(HERE, "..", "src", "predef_a64_gen.goose")).read()
    m = re.search(r'let A64_DELTA = """\n(.*?)\n""";', d, re.S)
    added = [l.split()[1] for l in m.group(1).splitlines() if l.startswith("0 ") and not l.endswith(" 0")]
    # and the target builtins clang's AArch64 headers call (their names are not all strings of libclang-cpp)
    inc = "/usr/lib/llvm-20/lib/clang/20/include"
    hdr = set()
    for h in ("arm_acle.h", "arm_neon.h", "arm_fp16.h", "arm_bf16.h", "arm_vector_types.h"):
        if os.path.exists(os.path.join(inc, h)):
            hdr |= set(re.findall(r"__builtin_(?:arm|neon|aarch64)_\w+", open(os.path.join(inc, h)).read()))
    names = sorted(set(x86) | set(added) | hdr)
    names = [n for n in names if not n.startswith("__is_") and not n.startswith("_Block")]
    # in chunks: clang stops on some of the target builtins' probes (a crash takes its chunk only)
    types = {}
    for k in range(0, len(names), 150):
        part = names[k:k + 150]
        t1 = probe(a.clang, part, "", flags)
        if not t1:
            for n in part:
                t1.update(probe(a.clang, [n], "", flags))
        types.update(t1)
        with_file = probe(a.clang, [n for n in part if "printf" in n or "scanf" in n or "FILE" in types.get(n, ("", ""))[0]],
                          "typedef struct _IO_FILE FILE;\n", flags)
        for n, (t, f) in with_file.items():
            if "FILE" in t and types.get(n, ("", ""))[0] != t:
                types[n] = (t, f)
    lines = []
    for n in names:
        if n not in types:
            continue
        t, f = types[n]
        # C has no references: va_start / va_copy / va_end take the va_list's address
        t = t.replace("__builtin_va_list &", "__builtin_va_list *")
        if n in x86:
            xt, xf = x86[n]
            f = xf if "n" in xf else f
            if t == xt:
                continue
        lines.append("%s|%s|%s" % (n, t, f))
    print(f"{len(lines)} AArch64 builtin lines", file=sys.stderr)
    out = os.path.join(HERE, "..", "src", "builtins_a64_gen.goose")
    with open(out, "w") as f:
        f.write("// Generated by tools/gen_builtins.py --a64 from clang-20 --target=aarch64-linux-gnu. Do not edit.\n")
        f.write("// name|type|flags of the builtins whose type differs from builtins_gen.goose's or that only AArch64 has\n")
        f.write('let BUILTIN_TYPES_A64 = """\n' + "\n".join(lines) + '\n""";\n')


if __name__ == "__main__":
    main()
