#!/usr/bin/env python3
"""Generate src/tables_gen.goose: hash tables over the generated name tables.

goosecc looks names up in the text tables of predef_gen.goose (the answers to
__has_builtin, __has_attribute, ... and the warning options) and of
builtins_gen.goose (the types of the builtin functions). Interning every name
of a table into the identifier table at its first use cost about 0.3 ms per
translation unit, more than many CTMark files spend parsing; these tables are
static data instead (`const` arrays), built here from the same text:

  TBL_<NAME>_OFF  the offset of each entry's line in the text
  TBL_<NAME>_HT   open addressing over common.goose's hash_bytes (goosecc_rt.h) of
                  the entry's name: entry index + 1, 0 = empty, linear probing
  TBL_<NAME>_LEN  the length of the text, checked at the first lookup, so
                  that tables left stale by a regenerated text are an error

The name of an entry is its line up to the first ' ' (predef tables) or '|'
(BUILTIN_TYPES). Of two entries with one name the later wins, as the
dictionary that the tables replace did.

Run it after tools/gen_predef.py, tools/gen_predef_cxx.py or tools/gen_builtins.py.

usage: tools/gen_tables.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")
OUT = os.path.join(SRC, "tables_gen.goose")

PREDEF_TABLES = ["HAS_BUILTIN", "HAS_FEATURE", "HAS_EXTENSION", "HAS_ATTRIBUTE", "HAS_C_ATTRIBUTE",
                 "HAS_DECLSPEC_ATTRIBUTE", "WARNING_OPTIONS"]
# D1: C++ mode (predef_cxx_gen.goose, tools/gen_predef_cxx.py)
PREDEF_CXX_TABLES = ["HAS_CXX_BUILTIN", "HAS_CXX_FEATURE", "HAS_CXX_EXTENSION", "HAS_CXX_ATTRIBUTE",
                     "HAS_CXX_CPP_ATTRIBUTE", "HAS_CXX_DECLSPEC_ATTRIBUTE", "CXX_KEYWORDS"]


def goose_text(path, name):
    """The content of `let NAME = \"\"\"...\"\"\";` as Goose sees it (§2: the lines between, joined by \\n)."""
    text = open(path).read()
    m = re.search(r'^let ' + name + r' = """\n(.*?)\n""";', text, re.S | re.M)
    if not m:
        raise SystemExit(f"{path}: no table {name}")
    return m.group(1).encode()


M64 = (1 << 64) - 1


def hash_bytes(s):
    """goosecc_hash_mem (goosecc_rt.h): 8-byte little-endian words, the last
    holding what remains; h = (h ^ w) * K, then mixed."""
    K = 0xff51afd7ed558ccd
    h = 0x9e3779b97f4a7c15
    words = [s[i:i + 8] for i in range(0, len(s), 8)]
    for w in words:
        h = ((h ^ int.from_bytes(w, "little")) * K) & M64
    h ^= h >> 32
    h = (h * K) & M64
    h ^= h >> 29
    return h & 0xFFFFFFFF


def entries(text, seps):
    out = []    # (name, line offset)
    i = 0
    while i <= len(text):
        j = i
        while j < len(text) and text[j] not in seps and text[j] != 10:
            j += 1
        if j > i:
            out.append((text[i:j], i))
        k = text.find(b"\n", i)
        if k < 0:
            break
        i = k + 1
    return out


def table(name, text, seps):
    es = entries(text, seps)
    last = {}
    for k, (nm, off) in enumerate(es):
        last[nm] = k
    keep = [k for k, (nm, off) in enumerate(es) if last[nm] == k]
    size = 2
    while size < 2 * max(len(keep), 1):
        size *= 2
    ht = [0] * size
    offs = [es[k][1] for k in keep]
    for idx, k in enumerate(keep):
        p = hash_bytes(es[k][0]) & (size - 1)
        while ht[p]:
            p = (p + 1) & (size - 1)
        ht[p] = idx + 1
    assert len(offs) < 65535

    def arr(ty, vals):
        lines = []
        for s in range(0, len(vals), 20):
            lines.append("    " + ", ".join(str(v) for v in vals[s:s + 20]) + ",")
        return f"const u{ty}[{len(vals)}] = [\n" + "\n".join(lines) + "\n];\n"

    return (f"let TBL_{name}_LEN = {len(text)};\n"
            f"let TBL_{name}_OFF: " + arr(32, offs if offs else [0]) +
            f"let TBL_{name}_HT: " + arr(16, ht))


def main():
    parts = ["// Generated by tools/gen_tables.py from predef_gen.goose and builtins_gen.goose. Do not edit.\n",
             "// Hash tables over their name tables (see the generator).\n\n"]
    for t in PREDEF_TABLES:
        parts.append(table(t, goose_text(os.path.join(SRC, "predef_gen.goose"), t), b" "))
        parts.append("\n")
    parts.append(table("BUILTIN_TYPES", goose_text(os.path.join(SRC, "builtins_gen.goose"), "BUILTIN_TYPES"), b"|"))
    for t in PREDEF_CXX_TABLES:
        parts.append("\n")
        parts.append(table(t, goose_text(os.path.join(SRC, "predef_cxx_gen.goose"), t), b" "))
    with open(OUT, "w") as f:
        f.write("".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
